def key(code):
    return ('Object(InputEventKey,"resource_local_to_scene":false,"resource_name":"","device":-1,"window_id":0,'
            '"alt_pressed":false,"shift_pressed":false,"ctrl_pressed":false,"meta_pressed":false,"pressed":false,'
            '"keycode":0,"physical_keycode":%d,"key_label":0,"unicode":0,"location":0,"echo":false,"script":null)' % code)


def joyb(btn, dev=0):
    return ('Object(InputEventJoypadButton,"resource_local_to_scene":false,"resource_name":"","device":%d,'
            '"button_index":%d,"pressure":0.0,"pressed":false,"script":null)' % (dev, btn))


def joya(axis, val, dev=0):
    return ('Object(InputEventJoypadMotion,"resource_local_to_scene":false,"resource_name":"","device":%d,'
            '"axis":%d,"axis_value":%.1f,"script":null)' % (dev, axis, val))


def action(name, events, dz=0.5):
    return '%s={\n"deadzone": %.1f,\n"events": [%s]\n}\n' % (name, dz, ', '.join(events))


def players():
    out = ''
    # Player 1: WASD + JKUI + L, gamepad 0
    p1 = {
        'left': [key(KEY['A']), joyb(13, 0), joya(0, -1.0, 0)],
        'right': [key(KEY['D']), joyb(14, 0), joya(0, 1.0, 0)],
        'up': [key(KEY['W']), joyb(11, 0), joya(1, -1.0, 0)],
        'down': [key(KEY['S']), joyb(12, 0), joya(1, 1.0, 0)],
        'lp': [key(KEY['J']), joyb(2, 0)],
        'hp': [key(KEY['K']), joyb(3, 0)],
        'lk': [key(KEY['U']), joyb(0, 0)],
        'hk': [key(KEY['I']), joyb(1, 0)],
        'block': [key(KEY['L']), joyb(10, 0)],
    }
    # Player 2: arrows + numpad (or , . M / and N), gamepad 1
    p2 = {
        'left': [key(KEY['LEFT']), joyb(13, 1), joya(0, -1.0, 1)],
        'right': [key(KEY['RIGHT']), joyb(14, 1), joya(0, 1.0, 1)],
        'up': [key(KEY['UP']), joyb(11, 1), joya(1, -1.0, 1)],
        'down': [key(KEY['DOWN']), joyb(12, 1), joya(1, 1.0, 1)],
        'lp': [key(KEY['KP4']), key(KEY['COMMA']), joyb(2, 1)],
        'hp': [key(KEY['KP5']), key(KEY['PERIOD']), joyb(3, 1)],
        'lk': [key(KEY['KP1']), key(KEY['M']), joyb(0, 1)],
        'hk': [key(KEY['KP2']), key(KEY['SLASH']), joyb(1, 1)],
        'block': [key(KEY['KP6']), key(KEY['N']), joyb(10, 1)],
    }
    for pfx, mp in (('p1_', p1), ('p2_', p2)):
        for k, ev in mp.items():
            out += action(pfx + k, ev)
    out += action('pause', [key(KEY['ESC']), key(KEY['P']), joyb(6, 0), joyb(6, 1)])
    out += action('debug_hitboxes', [key(KEY['F1'])])
    out += action('training_reset', [key(KEY['BACKSPACE']), joyb(4, 0)])
    return out


