def font():
    CW, CH = 6, 9
    img = Image(16 * CW, 6 * CH)
    white = (255, 255, 255, 255)
    for code in range(32, 128):
        ch = chr(code)
        g = G.get(ch.upper(), G.get(ch, G['?'] if code < 127 else G[' ']))
        idx = code - 32
        ox, oy = (idx % 16) * CW, (idx // 16) * CH
        for y, row in enumerate(g):
            for x, c in enumerate(row):
                if c == '#':
                    img.set(ox + x, oy + y, white)
    os.makedirs(os.path.join(ROOT, 'assets', 'fonts'), exist_ok=True)
    img.save(os.path.join(ROOT, 'assets', 'fonts', 'pixel_font.png'))


def big_text(img, text, x0, y0, s, top, bot, outline, bevel_hi, slant=0.0):
    """Chunky metallic title lettering built from the 5x7 glyphs at scale s."""
    mask = set()
    for i, ch in enumerate(text):
        g = G.get(ch, G[' '])
        for y, row in enumerate(g):
            for x, c in enumerate(row):
                if c == '#':
                    for yy in range(s):
                        for xx in range(s):
                            py = y * s + yy
                            px = i * 6 * s + x * s + xx + int((7 * s - py) * slant)
                            mask.add((px, py))
    h = 7 * s
    # outline (2px) then fill with vertical chrome gradient + bevel highlight
    for (px, py) in list(mask):
        for dx in (-2, -1, 0, 1, 2):
            for dy in (-2, -1, 0, 1, 2, 3):
                if (px + dx, py + dy) not in mask:
                    img.set(x0 + px + dx, y0 + py + dy, outline)
    for (px, py) in mask:
        t = py / h
        band = int(t * 6) / 5
        c = tuple(int(top[k] + (bot[k] - top[k]) * band) for k in range(3)) + (255,)
        if (px, py - 1) not in mask:
            c = bevel_hi
        elif 0.47 < t < 0.53:
            c = tuple(min(255, int(v * 1.25)) for v in c[:3]) + (255,)
        img.set(x0 + px, y0 + py, c)


def logo():
    W, H = 420, 150
    img = Image(W, H)
    # "MAN" warm, "VS" in a red badge, "MACHINE" cold steel
    big_text(img, 'MAN', 147, 6, 7, hexc('#ffe08a'), hexc('#c0461c'), hexc('#1a0806'), hexc('#fff6d0'), 0.12)
    # VS badge
    cx, cy = 210, 74
    for y in range(-16, 17):
        for x in range(-28, 29):
            if abs(x) / 28 + abs(y) / 16 <= 1:
                img.set(cx + x, cy + y, hexc('#c8141a') if abs(x) / 28 + abs(y) / 16 < 0.86 else hexc('#ffd84a'))
    big_text(img, 'VS', 192, 64, 3, hexc('#ffffff'), hexc('#ffd0a0'), hexc('#3a0204'), hexc('#ffffff'), 0.0)
    big_text(img, 'MACHINE', 80, 96, 6, hexc('#e8f4ff'), hexc('#3a5a8a'), hexc('#04060e'), hexc('#ffffff'), 0.12)
    img.save(os.path.join(ROOT, 'assets', 'ui', 'logo.png'))


def icon():
    img = Image(64, 64, hexc('#120a0c'))
    for y in range(64):
        for x in range(64):
            if x + y < 64:
                img.set(x, y, hexc('#6a1418'))
            else:
                img.set(x, y, hexc('#1a2a48'))
    big_text(img, 'MV', 10, 18, 4, hexc('#ffe08a'), hexc('#c0461c'), hexc('#000000'), hexc('#ffffff'))
    img.save(os.path.join(ROOT, 'assets', 'ui', 'icon.png'))


